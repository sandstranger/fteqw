"""mkstatic.py <nm -A output of every object>

Daikatana's game was three DLLs (physics, world, weapons) and IonCommon (user/) linked into each. Here they're
linked together, so:
- what more than one of them defined (each DLL had its own) is renamed in physics and weapons, with a #define
  in include/dk_rename_<module>.h (dk_fte_compat.h includes it when DK_MODULE_<MODULE> is defined); world keeps
  its names.
- what world and weapons exported (extern "C", which GetProcAddress found by name) goes into physics/dk_exports.cpp's
  tables, for DLL_FindFunction.

Run it on objects built with the current rename headers: it reads them to see through their renames. Object
names are obj/<module>_<path>.o (any directory, any prefix before <module>_ that has no _)."""
import os, re, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
MODULES = ('physics', 'world', 'weapons', 'user')
RENAMED = {'physics': 'dkph_', 'weapons': 'dkwp_'}

def demangled_base(sym):
    """the identifier a symbol was declared with: extern "C" ones and globals as they are, C++ functions from
    their mangled name (_Z<len><name>...), None for anything nested (classes, namespaces)"""
    if not sym.startswith('_Z'):
        return sym
    m = re.match(r'_Z(\d+)', sym)
    if not m:
        return None
    n = int(m.group(1))
    start = m.end()
    return sym[start:start + n]

class Out:
    """a file written only when what's in it changes (so make doesn't rebuild everything that includes it)"""
    def __init__(self, path):
        self.path, self.parts = path, []
    def write(self, s):
        self.parts.append(s)
    def __enter__(self):
        return self
    def __exit__(self, *exc):
        text = ''.join(self.parts)
        try:
            old = open(self.path, newline='').read()
        except OSError:
            old = None
        if old != text:
            open(self.path, 'w', newline='\n').write(text)

def main():
    defs = collections.defaultdict(set)		# identifier -> modules defining it
    cfuncs = collections.defaultdict(set)	# module -> extern "C" functions
    for line in open(sys.argv[1], encoding='utf-8', errors='replace'):
        m = re.match(r'(?:.*/)?obj/(?:\w+?_)??(physics|world|weapons|user)_(.+?)\.o:\s*([0-9a-f]*)\s+(\w)\s+(\S+)$', line.strip())
        if not m:
            continue
        mod, f, addr, typ, sym = m.groups()
        if typ not in 'TDBRC':
            continue	# undefined, weak (inline functions, templates), local
        base = demangled_base(sym)
        if not base:
            continue
        pre = RENAMED.get(mod)
        if pre and base.startswith(pre):
            base = base[len(pre):]
        defs[base].add(mod)
        if typ == 'T' and not sym.startswith('_Z'):
            cfuncs[mod].add(base)

    renames = {'physics': set(), 'weapons': set()}
    for base, mods in defs.items():
        if len(mods) < 2:
            continue
        if 'user' in mods:
            print('warning: %s in user and %s' % (base, sorted(mods)))
        for mod in mods:
            if mod in renames:
                renames[mod].add(base)
    for mod, names in renames.items():
        path = os.path.join(HERE, 'include', 'dk_rename_%s.h' % mod)
        with Out(path) as f:
            f.write('/* generated by mkstatic.py: what %s defined that another of Daikatana\'s DLLs did too */\n' % mod)
            for n in sorted(names):
                f.write('#define %s %s%s\n' % (n, RENAMED[mod], n))
        print('%s: %d renames' % (mod, len(names)))

    path = os.path.join(HERE, 'fte', 'dk_exports.cpp')
    with Out(path) as f:
        f.write('/* generated by mkstatic.py: what world and weapons exported, as GetProcAddress found it */\n')
        f.write('#include "dk_exports.h"\n\n')
        for mod in ('world', 'weapons'):
            f.write('extern "C" {\n')
            for n in sorted(cfuncs[mod]):
                real = (RENAMED[mod] + n) if mod in RENAMED and n in renames[mod] else n
                f.write('void %s(void);\n' % real)
            f.write('}\n')
        for mod in ('world', 'weapons'):
            f.write('\nconst dkexport_t dkexports_%s[] =\n{\n' % mod)
            for n in sorted(cfuncs[mod], key=lambda s: s.encode()):
                real = (RENAMED[mod] + n) if mod in RENAMED and n in renames[mod] else n
                f.write('\t{"%s", (void*)%s},\n' % (n, real))
            f.write('\t{0, 0}\n};\n')
        print('exports: world %d, weapons %d' % (len(cfuncs['world']), len(cfuncs['weapons'])))

main()

"""Builds engine/common/mapfixes.c: other engines' fixed entity lumps for maps with gameplay bugs in them.

usage: python tools/mapfixes.py --yq2 <yquake2>/stuff/mapfixes
                                --uh2 <uhexen2>/gamecode/mapfixes <hexen2 dir with data1/ and portals/>
                                > engine/common/mapfixes.c

- yquake2 (https://github.com/yquake2/yquake2) ships stuff/mapfixes/<game>/<map>@<crc>.ent for Quake 2 and its
  mission packs (monsters stuck in walls, triggers that can block progress, items out of reach...).
- uHexen2 (https://github.com/sezero/uhexen2) ships gamecode/mapfixes/<gamedir>/maps/<map>.ent for Hexen II and
  Portal of Praevus (a teleport that drops you, a prize that never spawns, objectives never cleared, a golem
  that dies stuck in its lift...), written against the v1.11 maps. They carry no crc, so it is taken here from
  the maps they were written for (the game's own paks), and a fix only ever replaces that map's lump.

<crc> is yquake2's CRC_Block (CRC16-CCITT, Quake's) of the map's own entity lump less its last byte. FTE carries
the fixes compressed in the engine and uses them when no .ent file overrides the map (gl_model.c,
Mod_LoadEntitiesBlob).
"""
import os
import re
import struct
import sys
import zlib


def crc_block(data):
    crc = 0xffff
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) if crc & 0x8000 else (crc << 1)
            crc &= 0xffff
    return crc


def pak_files(path):
    f = open(path, 'rb')
    ident, off, ln = struct.unpack('<4sii', f.read(12))
    f.seek(off)
    d = f.read(ln)
    for i in range(0, ln, 64):
        n, o, l = struct.unpack('<56sii', d[i:i + 64])
        yield n.split(b'\0')[0].decode('latin-1'), f, o, l


def bsp_entity_crc(bsp):
    if bsp[0:4] == b'IBSP':		# quake2: lump 0 after the version
        off, ln = struct.unpack('<ii', bsp[8:16])
    else:						# quake/hexen2 (bsp29, bsp2): lump 0 is the entities
        off, ln = struct.unpack('<ii', bsp[4:12])
    return crc_block(bsp[off:off + ln - 1])


fixes = []	# (game, name, crc, data)
args = sys.argv[1:]
while args:
    opt = args.pop(0)
    if opt == '--yq2':
        root = args.pop(0)
        for game in sorted(os.listdir(root)):
            for fname in sorted(os.listdir(os.path.join(root, game))):
                m = re.match(r'^(.+)@([0-9a-fA-F]{4})\.ent$', fname)
                if m:
                    data = open(os.path.join(root, game, fname), 'rb').read().replace(b'\r\n', b'\n')
                    fixes.append(('quake2 ' + game, m.group(1).lower(), int(m.group(2), 16), data))
    elif opt == '--uh2':
        root, h2dir = args.pop(0), args.pop(0)
        for gamedir in sorted(os.listdir(root)):
            mapdir = os.path.join(root, gamedir, 'maps')
            wanted = {f[:-4].lower(): f for f in os.listdir(mapdir) if f.endswith('.ent')}
            found = {}
            paks = sorted(p for p in os.listdir(os.path.join(h2dir, gamedir)) if p.lower().endswith('.pak'))
            for pak in paks:
                for name, f, o, l in pak_files(os.path.join(h2dir, gamedir, pak)):
                    base = os.path.basename(name).lower()
                    if name.lower().startswith('maps/') and base.endswith('.bsp') and base[:-4] in wanted:
                        f.seek(o)
                        found[base[:-4]] = bsp_entity_crc(f.read(l))
            for name in sorted(wanted):
                if name not in found:
                    sys.exit('no %s/maps/%s.bsp in %s to take its crc from' % (gamedir, name, h2dir))
                data = open(os.path.join(mapdir, wanted[name]), 'rb').read().replace(b'\r\n', b'\n')
                fixes.append(('hexen2 ' + gamedir, name, found[name], data))
    else:
        sys.exit(__doc__)

out = sys.stdout
out.write("""/*
Generated by tools/mapfixes.py: do not edit.

Other engines' fixed entity lumps for maps with gameplay bugs in them, GPL v2 or later as the engines that ship
them: yquake2's (Quake 2 and its mission packs; by BjossiAlfreds and others) and uHexen2's (Hexen II and Portal
of Praevus; by Thomas Freundt and others). Each is keyed by the map's name and the CRC16 of the map's own entity
lump, as yquake2 names its files (<map>@<crc>.ent), so a fix only ever replaces the lump it was written against.
Kept zlib-compressed.
*/
#include "quakedef.h"

#ifdef AVAIL_ZLIB
""")
for i, (game, name, crc, data) in enumerate(fixes):
    z = zlib.compress(data, 9)
    out.write("static const unsigned char mapfix%d[%d] = {	/*%s: %s@%04x.ent*/\n" % (i, len(z), game, name, crc))
    for j in range(0, len(z), 24):
        out.write("\t" + ",".join(str(b) for b in z[j:j + 24]) + ",\n")
    out.write("};\n")
out.write("""
static const struct
{
	const char *map;			//the map's name, without maps/ or .bsp
	unsigned short crc;			//of the map's own entity lump
	unsigned int size;			//uncompressed
	unsigned int csize;
	const unsigned char *data;	//zlib
} mapfixes[] =
{
""")
for i, (game, name, crc, data) in enumerate(fixes):
    out.write("\t{\"%s\", 0x%04x, %d, sizeof(mapfix%d), mapfix%d},	//%s\n" % (name, crc, len(data), i, i, game))
out.write("""};

size_t ZLib_DecompressBuffer(const qbyte *in, size_t insize, qbyte *out, size_t maxoutsize);
qboolean LibZ_Init(void);
#endif

/*
The fix for a map (maps/<name>.bsp) whose entity lump has this CRC16 (yquake2's CRC_Block of the lump
without its last byte): a BZ_Malloced, nul terminated entity string, or NULL when there is none.
*/
char *Mod_BuiltinMapFix(const char *modelname, unsigned int crc, size_t *size)
{
#ifdef AVAIL_ZLIB
	char name[MAX_QPATH];
	size_t i;
	char *ents;

	COM_FileBase(modelname, name, sizeof(name));
	for (i = 0; i < countof(mapfixes); i++)
	{
		if (mapfixes[i].crc != crc || Q_strcasecmp(mapfixes[i].map, name))
			continue;
		if (!LibZ_Init())
			return NULL;
		ents = BZ_Malloc(mapfixes[i].size + 1);
		if (ZLib_DecompressBuffer(mapfixes[i].data, mapfixes[i].csize, (qbyte*)ents, mapfixes[i].size) != mapfixes[i].size)
		{
			BZ_Free(ents);
			return NULL;
		}
		ents[mapfixes[i].size] = 0;
		*size = mapfixes[i].size;
		return ents;
	}
#endif
	return NULL;
}
""")

"""Builds engine/common/q2mapfixes.c from yquake2's map fixes.

usage: python tools/q2mapfixes.py <yquake2>/stuff/mapfixes > engine/common/q2mapfixes.c

yquake2 (https://github.com/yquake2/yquake2) ships stuff/mapfixes/<game>/<map>@<crc>.ent: replacement entity
lumps for maps of Quake 2 and its mission packs with gameplay bugs in them (monsters stuck in walls, triggers
that can block progress, items out of reach...). <crc> is the CRC16 of the map's own entity lump, so a fix only
ever replaces the lump of the very map it was written against. FTE carries them compressed in the engine and
uses them as yquake2 uses the files (gl_model.c, Mod_LoadEntitiesBlob).
"""
import os
import re
import sys
import zlib

root = sys.argv[1]
fixes = []
for game in sorted(os.listdir(root)):
    for fname in sorted(os.listdir(os.path.join(root, game))):
        m = re.match(r'^(.+)@([0-9a-fA-F]{4})\.ent$', fname)
        if not m:
            continue
        data = open(os.path.join(root, game, fname), 'rb').read().replace(b'\r\n', b'\n')
        fixes.append((game, m.group(1).lower(), int(m.group(2), 16), data))

out = sys.stdout
out.write("""/*
Generated by tools/q2mapfixes.py from yquake2's stuff/mapfixes: do not edit.

yquake2's map fixes: replacement entity lumps for Quake 2 maps with gameplay bugs in them (by BjossiAlfreds
and others, GPL v2 or later as yquake2). Each is keyed by the map's name and the CRC16 of the map's own
entity lump, exactly as yquake2 names the files (<map>@<crc>.ent), and kept zlib-compressed.
*/
#include "quakedef.h"

#ifdef AVAIL_ZLIB
""")
for i, (game, name, crc, data) in enumerate(fixes):
    z = zlib.compress(data, 9)
    out.write("static const unsigned char q2mapfix%d[%d] = {	/*%s/%s@%04x.ent*/\n" % (i, len(z), game, name, crc))
    for j in range(0, len(z), 24):
        out.write("\t" + ",".join(str(b) for b in z[j:j+24]) + ",\n")
    out.write("};\n")
out.write("""
static const struct
{
	const char *map;			//the map's name, without maps/ or .bsp
	unsigned short crc;			//of the map's own entity lump
	unsigned int size;			//uncompressed
	unsigned int csize;
	const unsigned char *data;	//zlib
} q2mapfixes[] =
{
""")
for i, (game, name, crc, data) in enumerate(fixes):
    out.write("\t{\"%s\", 0x%04x, %d, sizeof(q2mapfix%d), q2mapfix%d},	//%s\n" % (name, crc, len(data), i, i, game))
out.write("""};

size_t ZLib_DecompressBuffer(const qbyte *in, size_t insize, qbyte *out, size_t maxoutsize);
qboolean LibZ_Init(void);
#endif

/*
The fix for a map (maps/<name>.bsp) whose entity lump has this CRC16 (yquake2's CRC_Block of the lump
without its last byte): a BZ_Malloced, nul terminated entity string, or NULL when there is none.
*/
char *Mod_Q2MapFix(const char *modelname, unsigned int crc, size_t *size)
{
#ifdef AVAIL_ZLIB
	char name[MAX_QPATH];
	size_t i;
	char *ents;

	COM_FileBase(modelname, name, sizeof(name));
	for (i = 0; i < countof(q2mapfixes); i++)
	{
		if (q2mapfixes[i].crc != crc || Q_strcasecmp(q2mapfixes[i].map, name))
			continue;
		if (!LibZ_Init())
			return NULL;
		ents = BZ_Malloc(q2mapfixes[i].size + 1);
		if (ZLib_DecompressBuffer(q2mapfixes[i].data, q2mapfixes[i].csize, (qbyte*)ents, q2mapfixes[i].size) != q2mapfixes[i].size)
		{
			BZ_Free(ents);
			return NULL;
		}
		ents[q2mapfixes[i].size] = 0;
		*size = q2mapfixes[i].size;
		return ents;
	}
#endif
	return NULL;
}
""")
